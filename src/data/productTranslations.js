export const getLocalizedProduct = (product, lang = 'uz', tc = (c) => c, formatPrice = null) => {
  if (!product) return product
  const trans = PRODUCT_TRANSLATIONS[product.id]
  const curLang = ['uz', 'ru', 'en'].includes(lang) ? lang : 'uz'

  // Extract clean number if priceNum is missing
  let pNum = product.priceNum
  if (!pNum && typeof product.price === 'string') {
    const digits = product.price.replace(/[^\d]/g, '')
    if (digits) pNum = parseInt(digits, 10)
  }

  let oldPNum = product.oldPriceNum
  if (!oldPNum && typeof product.oldPrice === 'string') {
    const digits = product.oldPrice.replace(/[^\d]/g, '')
    if (digits) oldPNum = parseInt(digits, 10)
  }

  const curr = curLang === 'ru' ? 'сум' : curLang === 'en' ? 'UZS' : "so'm"

  const formatTextPrice = (origStr, numVal) => {
    if (typeof numVal === 'number' && !isNaN(numVal) && formatPrice) {
      return formatPrice(numVal)
    }
    if (!origStr) return ''
    return String(origStr).replace(/so'm|сум|UZS|sum/gi, curr)
  }

  if (curLang === 'uz' || !trans || !trans[curLang]) {
    return {
      ...product,
      categoryName: tc ? tc(product.category) : product.category,
      price: formatTextPrice(product.price, pNum),
      oldPrice: product.oldPrice ? formatTextPrice(product.oldPrice, oldPNum) : null
    }
  }

  const lData = trans[curLang]
  return {
    ...product,
    name: lData.name || product.name,
    description: lData.description || product.description,
    specs: lData.specs || product.specs,
    badge: lData.badge || product.badge,
    categoryName: tc ? tc(product.category) : product.category,
    price: formatTextPrice(product.price, pNum),
    oldPrice: product.oldPrice ? formatTextPrice(product.oldPrice, oldPNum) : null
  }
}
